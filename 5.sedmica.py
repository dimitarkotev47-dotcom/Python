n = int(input("Въведете число от 1 до 7:"))
if n == 1:
    print("Понеделник") 
elif n == 2:
    print("Вторник")
elif n == 3:
    print("Сряда")      
elif n == 4:
    print("Четвъртък")
elif n == 5:
    print("Петък")
elif n == 6:
    print("Събота")
elif n == 7:
    print("Неделя")
else:
    print("Въведете валидна стойност!")